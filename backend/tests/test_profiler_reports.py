"""
Tests for Performance Profiler, Bottlenecks & Executive Reports (CSV & PDF)
"""
import time
from backend.app.services.profiler_service import profile_execution
from backend.tests.test_metrics_api import helper_register_server, make_sample_payload


def test_profiler_decorator():
    @profile_execution(threshold_ms=10.0)
    def simulated_computation():
        total = 0
        for i in range(100000):
            total += i
        return total

    res = simulated_computation()
    assert res > 0


def test_server_profiler_endpoint(client, test_user_and_org):
    headers = test_user_and_org["headers"]
    server_id, agent_token = helper_register_server(client, headers, "Profiler-Node")
    agent_headers = {"X-Agent-Token": agent_token, "X-Server-ID": server_id}

    # Ingest metric with high CPU and RAM
    client.post("/api/agent/metrics", json=make_sample_payload(server_id, cpu=88.0, ram=92.0), headers=agent_headers)

    r = client.get(f"/api/profiler/server/{server_id}", headers=headers)
    assert r.status_code == 200
    data = r.json()
    assert "bottlenecks" in data
    assert len(data["bottlenecks"]) >= 2  # CPU and RAM bottlenecks flagged


def test_daily_and_weekly_reports(client, test_user_and_org):
    headers = test_user_and_org["headers"]
    server_id, agent_token = helper_register_server(client, headers, "Report-Node")
    agent_headers = {"X-Agent-Token": agent_token, "X-Server-ID": server_id}
    client.post("/api/agent/metrics", json=make_sample_payload(server_id, cpu=50.0), headers=agent_headers)

    # 1. Daily
    daily = client.get("/api/reports/daily", headers=headers)
    assert daily.status_code == 200
    assert daily.json()["period_days"] == 1
    assert daily.json()["metrics_analyzed"] >= 1

    # 2. Weekly
    weekly = client.get("/api/reports/weekly", headers=headers)
    assert weekly.status_code == 200
    assert weekly.json()["period_days"] == 7


